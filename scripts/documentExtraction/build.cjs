/* global __dirname */
// Run after dependency updates; generated source is committed for offline use.
const { build } = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
(async () => {
  const result = await build({ entryPoints: [path.join(root, 'components/documentExtraction/runtime.js')],
    bundle: true, write: false, format: 'iife', platform: 'browser', target: ['safari16.4', 'chrome110'],
    minify: true, legalComments: 'eof' });
  const source = result.outputFiles[0].text;
  fs.writeFileSync(path.join(root, 'components/documentExtraction/bundle.generated.js'),
    '// Generated by scripts/documentExtraction/build.cjs. Do not edit.\nmodule.exports = ' + JSON.stringify(source) + ';\n');
  fs.writeFileSync(path.join(root, 'components/documentExtraction/THIRD_PARTY_NOTICES.txt'),
    ['pdfjs-dist/LICENSE', 'mammoth/LICENSE', 'dompurify/LICENSE'].map(file => file + '\n' + fs.readFileSync(path.join(root, 'node_modules', file), 'utf8')).join('\n\n'));
})().catch(error => { console.error(error); process.exitCode = 1; });
